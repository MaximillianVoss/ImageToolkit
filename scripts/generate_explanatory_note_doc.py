def create_base_document_from_template() -> None:
    BASE_DOCX_PATH.parent.mkdir(parents=True, exist_ok=True)

    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0

    try:
        document = word.Documents.Add(str(TEMPLATE_PATH))
        document.SaveAs2(str(BASE_DOCX_PATH), FileFormat=12)
        document.Close(False)
    finally:
        word.Quit()


def add_center_title(document: Document, text: str, size: int = 14) -> None:
    paragraph = document.add_paragraph(style=TEXT_STYLE)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run(text)
    run.bold = True
    run.font.size = Pt(size)


def add_caption(document: Document, text: str, centered: bool) -> None:
    paragraph = document.add_paragraph(style=CAPTION_STYLE)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if centered else WD_ALIGN_PARAGRAPH.LEFT
    paragraph.add_run(text)


def add_table_with_caption(
    document: Document,
    caption: str,
    headers: list[str],
    rows: list[tuple[str, ...]],
) -> None:
    add_caption(document, caption, centered=False)

    table = document.add_table(rows=1, cols=len(headers))
    table.style = TABLE_STYLE

    for cell, value in zip(table.rows[0].cells, headers, strict=True):
        cell.text = value

    for row in rows:
        cells = table.add_row().cells
        for cell, value in zip(cells, row, strict=True):
            cell.text = value

    add_text_paragraph(document)


def add_figure(document: Document, image_path: Path, caption: str, description: str) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.add_run().add_picture(str(image_path), width=Inches(6.35))

    add_caption(document, caption, centered=True)
    add_text_paragraph(document, description)


