def main() -> None:
    include_testing = "--without-testing" not in sys.argv[1:]
    output_docx_path = OUTPUT_DOCX_PATH if include_testing else OUTPUT_DOCX_NO_TESTING_PATH
    output_pdf_path = OUTPUT_PDF_PATH if include_testing else OUTPUT_PDF_NO_TESTING_PATH

    ensure_directories()
    create_base_document_from_template()
    try:
        initial_ui, processed_ui = capture_screenshots()
    except Exception:
        initial_ui = ROOT / "tmp" / "docs" / "ui_screens" / "initial-ui.png"
        processed_ui = ROOT / "tmp" / "docs" / "ui_screens" / "processed-ui.png"

    document = Document(BASE_DOCX_PATH)
    clear_document_body(document)
    document.core_properties.title = "Пояснительная записка к проекту ImageToolkit"
    document.core_properties.subject = "Пояснительная записка"
    document.core_properties.author = "Codex"
    document.sections[0].different_first_page_header_footer = True

    add_title_page(document)
    add_contents_page(document)
    add_introduction_section(document, include_testing=include_testing)
    add_domain_analysis_section(document, include_testing=include_testing)
    add_design_section(document, include_testing=include_testing)
    add_implementation_section(document, initial_ui, processed_ui, include_testing=include_testing)
    add_testing_section(document, include_testing=include_testing)
    add_user_guide_section(document)
    add_conclusion_section(document, include_testing=include_testing)
    add_sources_section(document, include_testing=include_testing)

    document.save(output_docx_path)
    update_fields_and_export_pdf(output_docx_path, output_pdf_path)

    print(output_docx_path)
    print(output_pdf_path)


if __name__ == "__main__":
    main()
