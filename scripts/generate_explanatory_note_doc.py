def start_chapter(document: Document, title: str) -> None:
    document.add_page_break()
    add_heading(document, title, level=1)


def add_numbered_paragraphs(document: Document, items: list[str]) -> None:
    for index, item in enumerate(items, start=1):
        add_text_paragraph(document, f"{index}. {item}")


def add_text_block(document: Document, text: str) -> None:
    normalized = dedent(text).strip()
    for raw_paragraph in normalized.split("\n\n"):
        paragraph = " ".join(line.strip() for line in raw_paragraph.splitlines() if line.strip())
        if paragraph:
            add_text_paragraph(document, paragraph)


def add_bullets(document: Document, items: list[str]) -> None:
    for item in items:
        add_text_paragraph(document, f"- {item}")


